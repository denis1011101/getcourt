if ENV["SEED_ENQUEUE_GEOCODING"].to_s == "1" && rows_to_insert.any?
  inserted_ids = Court.where(name: rows_to_insert.map { |r| r[:name] }).pluck(:id)
  pause_ms = ENV["SEED_GEOCODING_ENQUEUE_PAUSE_MS"].to_s.strip
  pause_s = pause_ms.empty? ? 0.0 : [ pause_ms.to_f / 1000.0, 0.0 ].max
  puts "Geocoding enqueue pause: #{(pause_s * 1000).round}ms between batches"
  inserted_ids.each_slice(100) do |ids|
    ids.each { |id| Geocoding::FetchCourtAddressJob.perform_later(id) }
    sleep(pause_s) if pause_s.positive?
  end
  puts "Enqueued geocoding jobs: #{inserted_ids.size}"
end

